"""Target facts and the per-target Spack requirements scope.

Target facts come from the committed registry (containers/images/targets.json)
and are selected by target id — never probed from the running machine. This
module renders them as a `packages.yaml` requirements scope that release.sh
drops into its command-line scope directory.

CUDA architecture policy is a package requirement, never root-spec text. A
requirement binds every instance of the package — including ones that only
appear transitively, such as gdrcopy under ucx/libfabric — whereas decorating
root specs can only reach packages an operator happened to name in the catalog.
Stdlib only: this must run under a bare system python3 on a builder.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Final

from chapar.common.jsonio import fail, load_json, mapping, string, strings

#: Packages whose CUDA support is unconditional: a bare requirement is correct
#: and a `when: +cuda` clause would be meaningless.
CUDA_ARCH_UNCONDITIONAL: Final = (
    "gdrcopy",
    "nccl",
    "nccl-tests",
    "nvbandwidth",
    "nvshmem",
    "nvtop",
)
#: Packages with an optional CUDA variant: gate on `+cuda` so a non-CUDA
#: concretization of the same package stays solvable.
CUDA_ARCH_WHEN_CUDA: Final = (
    "babelstream",
    "caliper",
    "hwloc",
    "libfabric",
    "openmpi",
    "ucx",
)
TARGETS_SCHEMA: Final = "https://nscaledev.github.io/chapar/schemas/vlad-image-targets/v1"


@dataclass(frozen=True, slots=True)
class TargetFacts:
    identifier: str
    oci_platform: str
    native_arch: str
    spack_target: str
    llvm_targets: tuple[str, ...]
    cuda_arch: tuple[str, ...]


def default_targets_path() -> Path:
    return Path(__file__).resolve().parents[3] / "containers/images/targets.json"


def load_targets(path: Path) -> dict[str, TargetFacts]:
    document = load_json(path)
    if document.get("schema") != TARGETS_SCHEMA:
        fail(f"unsupported target registry schema: {document.get('schema')}")
    if document.get("schema_version") != 1:
        fail("unsupported target registry schema version")
    raw_targets = mapping(document.get("targets"), "targets")
    if not raw_targets:
        fail("target registry has no targets")
    targets: dict[str, TargetFacts] = {}
    for identifier, raw in raw_targets.items():
        entry = mapping(raw, f"targets.{identifier}")
        unknown = set(entry) - {"oci_platform", "native_arch", "spack_target", "llvm_targets", "cuda_arch"}
        if unknown:
            fail(f"targets.{identifier} has unknown fields: {sorted(unknown)}")
        targets[identifier] = TargetFacts(
            identifier=identifier,
            oci_platform=string(entry.get("oci_platform"), f"targets.{identifier}.oci_platform"),
            native_arch=string(entry.get("native_arch"), f"targets.{identifier}.native_arch"),
            spack_target=string(entry.get("spack_target"), f"targets.{identifier}.spack_target"),
            llvm_targets=strings(entry.get("llvm_targets"), f"targets.{identifier}.llvm_targets"),
            cuda_arch=strings(entry.get("cuda_arch"), f"targets.{identifier}.cuda_arch"),
        )
    return targets


def resolve_target(path: Path, identifier: str) -> TargetFacts:
    targets = load_targets(path)
    facts = targets.get(identifier)
    if facts is None:
        fail(f"unknown target: {identifier} (registry has: {', '.join(sorted(targets))})")
    return facts


def _quote(value: str) -> str:
    """YAML-safe double quoting for requirement strings."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_packages_yaml(facts: TargetFacts) -> str:
    """The packages.yaml text for one target's requirements scope.

    Rendered by hand rather than through a YAML library so the output is
    byte-stable and this module stays stdlib-only.
    """
    lines = [
        f"# Generated by `chapar target scope --target {facts.identifier}`. Do not edit.",
        "packages:",
        "  all:",
        "    require:",
        f"    - {_quote(f'target={facts.spack_target}')}",
    ]
    llvm_targets = ",".join(facts.llvm_targets)
    if llvm_targets:
        lines += ["  llvm:", "    require:", f"    - {_quote(f'targets={llvm_targets}')}"]
    cuda_arch = ",".join(facts.cuda_arch)
    if cuda_arch:
        for name in CUDA_ARCH_UNCONDITIONAL:
            lines += [f"  {name}:", "    require:", f"    - {_quote(f'cuda_arch={cuda_arch}')}"]
        for name in CUDA_ARCH_WHEN_CUDA:
            lines += [
                f"  {name}:",
                "    require:",
                f"    - spec: {_quote(f'cuda_arch={cuda_arch}')}",
                f"      when: {_quote('+cuda')}",
            ]
    return "\n".join(lines) + "\n"
